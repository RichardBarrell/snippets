import { scrypt, randomBytes, timingSafeEqual } from "node:crypto";

const keylen = 64;
const maxmem = 260 * 1024 * 1024;

/**
 * Hashes a password with scrypt
 *
 * @param {string} password
 * @returns a string like '$scrypt$...' which you can safely save in a text file or DB
 */
async function makeHashedPassword(password: string) {
  const salt = randomBytes(16);
  return await rawMakeHashedPassword(password, salt);
}

/**
 * Checks a user password against a saved hash.
 *
 * @param {string} passwordFromUser     - raw password from the user
 * @param {string} hashedPasswordFromDB - should have been generated by makeHashedPassword()
 * @returns
 */
async function checkPasswordAgainstHashedPassword(
  passwordFromUser: string,
  hashedPasswordFromDB: string
) {
  if (typeof passwordFromUser !== "string")
    throw new Error("passwordFromUser should be a string");
  if (typeof hashedPasswordFromDB !== "string")
    throw new Error("hashedPasswordFromDB should be a string");

  const {
    cost,
    blockSize,
    parallelization,
    salt,
    hash: hashFromDB,
  } = parseHashedPassword(hashedPasswordFromDB);
  const hashFromUser = await new Promise<Buffer>((resolve, reject) => {
    scrypt(
      stringToBytes(passwordFromUser),
      salt,
      keylen,
      {
        cost,
        blockSize,
        parallelization,
        maxmem,
      },
      (error, result) => {
        if (error != null) reject(error);
        else resolve(result);
      }
    );
  });
  return timingSafeEqual(hashFromDB, hashFromUser);
}

export {
  makeHashedPassword,
  checkPasswordAgainstHashedPassword,
  rawMakeHashedPassword, // exported only for tests!
};

/**
 * Used internally by checkPasswordAgainstHashedPassword
 * Parses the format that makeHashedPassword() outputs.
 *
 * @param {string} hashedPassword
 * @returns all the parts from the hashed password
 */
function parseHashedPassword(hashedPassword: string) {
  const parts = hashedPassword.split("$");
  if (parts.length !== 5 || parts[1] !== "scrypt")
    throw new Error("scrypt: not an scrypt password");
  const m = /ln=(\d+),r=(\d+),p=(\d+)/.exec(parts[2]);
  if (m == null) throw new Error("scrypt: failed to extract param values");
  const cost = 1 << Number(m[1]);
  const blockSize = Number(m[2]);
  const parallelization = Number(m[3]);
  const salt = Buffer.from(parts[3], "base64");
  const hash = Buffer.from(parts[4], "base64");
  if (cost < 16384 || blockSize < 8 || parallelization <= 0)
    throw new Error("scrypt: silly parameter values");
  if (salt.length < 16) throw new Error("scrypt: dangerously small salt");
  if (hash.length < 16) throw new Error("scrypt: implausibly small hash");
  return {
    cost,
    blockSize,
    parallelization,
    salt,
    hash,
  };
}

function stringToBytes(password: string) {
  return new TextEncoder().encode(password.normalize("NFC"));
}

/**
 * Returns a base64 string without trailing "=" or "=="
 * @param {Buffer} bytes
 * @returns
 */
function bytesToBase64(bytes: Buffer) {
  const string = bytes.toString("base64");
  const m = /^([^=]*)=*$/.exec(string);
  if (!m) throw new Error("impossible error");
  return m[1];
}

/**
 * Internal implementation detail of makeHashedPassword()
 * Don't call this function from other modules.
 * This is only exported for tests! Don't call it!
 * @param {string} password
 * @param {bytes} salt
 * @returns
 */
async function rawMakeHashedPassword(password: string, salt: Buffer) {
  const cost = Math.pow(2, 17);
  const blockSize = 8;
  const parallelization = 1;
  const hash = await new Promise<Buffer>((resolve, reject) => {
    scrypt(
      stringToBytes(password),
      salt,
      keylen,
      {
        cost,
        blockSize,
        parallelization,
        maxmem,
      },
      (error, result) => {
        if (error != null) reject(error);
        else resolve(result);
      }
    );
  });
  const costLn2 = Math.log2(cost);
  return [
    "",
    "scrypt",
    `ln=${costLn2},r=${blockSize},p=${parallelization}`,
    bytesToBase64(salt),
    bytesToBase64(hash),
  ].join("$");
}
